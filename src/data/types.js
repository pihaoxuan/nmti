// 根据分数获取类型
export function getTypeByScores(scores) {
  const threshold = 8 // 超过这个分数就算"高"

  const S = scores.S >= threshold ? 'S' : 'N'
  const L = scores.L >= threshold ? 'L' : 'C'
  const E = scores.E >= threshold ? 'E' : 'I'
  const P = scores.P >= threshold ? 'P' : 'A'

  const code = S + L + E + P
  return types[code] || types.NLIA // 默认返回职场咸鱼
}
